const TRANSLATIONS: Readonly<Record<AppLanguage, TranslationTable>> = {
  'zh-CN': ZH_CN,
  en: EN,
  es: ES,
  fr: FR,
  de: DE,
  ja: JA,
  ko: KO,
};

function isLanguagePreference(value: string | null): value is LanguagePreference {
  return value === 'system' || SUPPORTED_LANGUAGES.some((language) => language.code === value);
}

function readStoredPreference(): LanguagePreference {
  try {
    const value = typeof window === 'undefined' ? null : window.localStorage.getItem(STORAGE_KEY);
    return isLanguagePreference(value) ? value : 'system';
  } catch {
    return 'system';
  }
}

export function resolveSystemLanguage(languages: readonly string[]): AppLanguage {
  for (const value of languages) {
    const normalized = value.trim().toLowerCase();
    const match = SUPPORTED_LANGUAGES.find(
      (language) =>
        normalized === language.code.toLowerCase() ||
        normalized.startsWith(`${language.code.toLowerCase()}-`) ||
        normalized.split('-')[0] === language.code.toLowerCase().split('-')[0],
    );
    if (match) {
      return match.code;
    }
  }
  return 'en';
}

function browserLanguages(): readonly string[] {
  if (typeof navigator === 'undefined') {
    return ['en'];
  }
  return navigator.languages?.length ? navigator.languages : [navigator.language];
}

@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly preferenceValue = signal<LanguagePreference>(readStoredPreference());
  private readonly detectedSystemLanguage = signal<AppLanguage>(
    resolveSystemLanguage(browserLanguages()),
  );

  readonly preference = this.preferenceValue.asReadonly();
  readonly activeLanguage = computed<AppLanguage>(() => {
    const preference = this.preferenceValue();
    return preference === 'system' ? this.detectedSystemLanguage() : preference;
  });
  readonly locale = computed(() => this.activeLanguage());
  readonly languages = SUPPORTED_LANGUAGES;
  readonly activeLanguageName = computed(
    () =>
      SUPPORTED_LANGUAGES.find((language) => language.code === this.activeLanguage())?.name ??
      'English',
  );
  readonly activeShortName = computed(
    () =>
      SUPPORTED_LANGUAGES.find((language) => language.code === this.activeLanguage())?.shortName ??
      'EN',
  );

  constructor() {
    effect(() => {
      const preference = this.preferenceValue();
      const language = this.activeLanguage();
      try {
        window.localStorage.setItem(STORAGE_KEY, preference);
      } catch {
        // Language switching remains available even if storage is disabled.
      }
      if (typeof document !== 'undefined') {
        document.documentElement.lang = language;
      }
    });

    if (typeof window !== 'undefined') {
      window.addEventListener('languagechange', () => {
        this.detectedSystemLanguage.set(resolveSystemLanguage(browserLanguages()));
      });
    }
  }

  setPreference(preference: LanguagePreference): void {
    if (isLanguagePreference(preference)) {
      this.preferenceValue.set(preference);
      try {
        window.localStorage.setItem(STORAGE_KEY, preference);
      } catch {
        // Language switching remains available even if storage is disabled.
      }
      if (typeof document !== 'undefined') {
        document.documentElement.lang = this.activeLanguage();
      }
    }
  }

  t(key: string, params: TranslationParams = {}): string {
    const value = TRANSLATIONS[this.activeLanguage()][key] ?? EN[key] ?? key;
    return value.replace(/\{(\w+)\}/g, (match, name: string) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
    );
  }

  formatTime(value: number | Date): string {
    return new Intl.DateTimeFormat(this.locale(), {
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: false,
    }).format(value);
  }

  /** Wall-clock moment for values that may fall outside today, such as an allowance reset. */
  formatDateTime(value: number | Date): string {
    return new Intl.DateTimeFormat(this.locale(), {
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    }).format(value);
  }
}
